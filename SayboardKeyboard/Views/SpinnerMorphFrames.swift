  private static func buildPath(from elements: [Element]) -> Path {
    var combined = Path()
    for element in elements {
      switch element {
      case .path(let svgString):
        combined.addPath(SVGPathParser.parse(svgString))
      case .rect(let x, let y, let rw, let rh, let rx):
        combined.addRoundedRect(
          in: CGRect(x: x, y: y, width: rw, height: rh),
          cornerSize: CGSize(width: rx, height: rx),
        )
      }
    }
    return combined
  }

